package domain

import (
	"regexp"
	"strings"
)

// Текстовый поиск по задачам. Правила простые и одинаковые везде:
//   - регистр не имеет значения;
//   - запрос с символами регулярного выражения ищется КАК регулярное выражение
//     (если оно валидно) — так находят «отчёт|акт» или «^Заказ \d+»;
//   - всё остальное ищется подстрокой, а служебные символы LIKE экранируются.

// regexMeta — признаки того, что человек написал регулярное выражение, а не
// просто фразу. Точку намеренно НЕ считаем: «т.к.» и сокращения с точками
// пишут в обычном поиске куда чаще, чем «любой символ».
var regexMeta = regexp.MustCompile(`[\\^$|?*+()\[\]{}]`)

// SearchRegex — запрос как регулярное выражение. ok=false — обычная подстрока
// (метасимволов нет либо выражение не компилируется: пользователь просто
// написал скобку, и падать из-за этого нельзя).
func SearchRegex(query string) (string, bool) {
	q := strings.TrimSpace(query)
	if q == "" || !regexMeta.MatchString(q) {
		return "", false
	}
	if _, err := regexp.Compile(q); err != nil {
		return "", false
	}
	return q, true
}

// EscapeLike — экранирование служебных символов ILIKE: «100%» ищется как
// «100%», а не как «100 и что угодно».
func EscapeLike(query string) string {
	r := strings.NewReplacer(`\`, `\\`, `%`, `\%`, `_`, `\_`)
	return r.Replace(strings.TrimSpace(query))
}
