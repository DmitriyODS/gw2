package domain

import "time"

/* Правовые документы платформы.

   Работать в приложении можно только приняв действующую редакцию: пока
   users.legal_version не равен LegalVersion, access-токен несёт клейм
   legal_required, и RequireAuth ВСЕХ сервисов отвечает 403 — гейт серверный,
   правкой localStorage его не обойти (тот же приём, что у force_change).

   Согласие на обработку персональных данных отделено от лицензии намеренно:
   ч.1 ст.9 152-ФЗ требует конкретного и предметного согласия, а «пакетная»
   галочка на лицензию с ПДн сразу таковой не является. Поэтому документов
   три, а галочек в плашке две (лицензия с политикой — одна, ПДн — вторая).

   Редакция общая на все документы: правка любого из них — новая LegalVersion,
   и платформа пересобирает согласия у всех. Версия ДУБЛИРУЕТСЯ на фронте
   (front/src/utils/legal.js) — тексты живут там, здесь только факт принятия. */
const LegalVersion = "1.0"

/* LegalGateEnabled — требовать ли согласие. Выключено: документы написаны, но
   реквизиты оператора в них ещё не заполнены, и показывать такой текст
   пользователям нельзя. Пока флаг снят, клейм legal_required не ставится
   НИКОМУ — значит ни один сервис доступ не закрывает; всё остальное (ручки,
   журнал согласий, колонки users) работает как обычно, поэтому включение =
   смена значения здесь.

   Парная константа фронта — LEGAL_CONSENT_VISIBLE в front/src/utils/release.js
   (она прячет плашку, страницу /legal и раздел настроек). Включать надо ОБЕ.

   Переменная, а не константа, ровно по одной причине: тесты включают гейт и
   проверяют его в рабочем режиме — иначе, пока флаг снят, блокировка не была
   бы покрыта вовсе. В рантайме её никто не меняет. */
var LegalGateEnabled = false

// LegalRequiredFor — обязан ли пользователь принять документы прямо сейчас.
// Единственная точка, где учитывается LegalGateEnabled: и клейм токена, и
// состояние для плашки считаются отсюда.
func LegalRequiredFor(u *User) bool {
	return LegalGateEnabled && !u.LegalAccepted()
}

// Ключи документов действующей редакции.
const (
	DocLicense = "license" // Лицензионное соглашение с конечным пользователем
	DocPrivacy = "privacy" // Политика конфиденциальности
	DocConsent = "consent" // Согласие на обработку персональных данных
)

// LegalRequiredDocuments — документы, без которых доступа нет. Все три
// обязательны; необязательные согласия (рассылки) сюда не добавлять — их отказ
// приложение не закрывает.
var LegalRequiredDocuments = []string{DocLicense, DocPrivacy, DocConsent}

// Consent — строка журнала согласий (доказательство факта для 152-ФЗ).
type Consent struct {
	ID         int64
	UserID     int64
	Version    string
	Documents  []string
	AcceptedAt time.Time
	RevokedAt  *time.Time
	IP         string
	UserAgent  string
}

// LegalAccepted — принята ли ДЕЙСТВУЮЩАЯ редакция документов. Прежняя редакция
// (или её отсутствие) равносильна отказу: гейт закрыт до нового согласия.
func (u *User) LegalAccepted() bool {
	return u != nil && u.LegalVersion != nil && *u.LegalVersion == LegalVersion
}
