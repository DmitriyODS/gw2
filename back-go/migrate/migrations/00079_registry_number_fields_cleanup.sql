-- Числовое поле реестра обязано хранить ЧИСЛО: сортировка приводит значение к
-- numeric, и одна ячейка с буквами роняла весь список (500 на каждый запрос
-- страницы). Сторож добавлен и в SQL сортировки, и в валидацию значений, но
-- мусор, уже лежащий в базе, надо убрать отдельно — этим и занята миграция.

-- 1. Инвентарные номера числовыми не бывают: «Пр-1», «ДОД25-1», «К-2». Поле
--    объявлено числовым по ошибке — переводим в текст. Значения при этом
--    остаются как есть (data-JSONB не трогаем), а поиск, сортировка и фильтр
--    начинают работать по-текстовому, как и ожидает человек.
UPDATE public.registry_fields
   SET type = 'text'
 WHERE type = 'number'
   AND label ILIKE '%инвентарн%';

-- 2. В оставшихся числовых полях нечисловые значения обнуляем: восстановить
--    задуманное число неоткуда, а «0» честно означает «не указано» и не мешает
--    ни сортировке, ни выгрузке. Пустые значения не трогаем — это законное
--    «не заполнено».
UPDATE public.registry_records r
   SET data = jsonb_set(r.data, ARRAY[f.id::text], '"0"'::jsonb)
  FROM public.registry_fields f
 WHERE f.registry_id = r.registry_id
   AND f.type = 'number'
   AND r.data ? f.id::text
   AND btrim(r.data ->> f.id::text) <> ''
   AND btrim(r.data ->> f.id::text) !~ '^[+-]?([0-9]+([.][0-9]*)?|[.][0-9]+)$';

-- 3. Количество отрицательным не бывает — ставим полю нижнюю границу 0.
--    Дальше границы задаются в настройках поля (Минимум/Максимум).
UPDATE public.registry_fields
   SET config = coalesce(config, '{}'::jsonb) || '{"min": 0}'::jsonb
 WHERE type = 'number'
   AND (label ILIKE '%кол-во%' OR label ILIKE '%количеств%')
   AND coalesce(config ->> 'min', '') = '';

