const groups = computed(() => {
  const q = query.value.trim().toLowerCase()
  if (!q) return GROUPS.value
  return GROUPS.value
    .map((g) => ({
      ...g,
      articles: g.articles.filter((a) => (
        [a.title, a.subtitle, ...(a.text || []), ...(a.tips || [])].join(' ').toLowerCase().includes(q)
      )),
    }))
    .filter((g) => g.articles.length)
})

